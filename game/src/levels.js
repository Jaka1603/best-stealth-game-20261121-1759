function buildBlocker(row) {
  if (row[0] === 'F') return { kind: 'fountain', x: row[1], y: row[2], r: row[3] };
  return {
    kind: row[0] === 'W' ? 'wall' : 'hedge',
    x: row[1], y: row[2], w: row[3], h: row[4],
  };
}

function buildGuard(row) {
  const guard = { path: row[0] };
  if (row.length > 1) guard.speedMul = row[1];
  return guard;
}

function buildGarden(row) {
  return {
    name: row[0],
    par: row[1],
    playerStart: { x: row[2], y: row[3] },
    exit: { x: row[4], y: row[5], w: row[6], h: row[7] },
    blockers: row[8].map(buildBlocker),
    shadows: row[9].map(([x, y, r]) => ({ x, y, r })),
    guards: row[10].map(buildGuard),
    moths: row[11],
  };
}

export const LEVELS = GARDENS.map(buildGarden);
