// nested objects. One row is one garden:
//
//   [ name, par, startX, startY, exitX, exitY, exitW, exitH,
//     blockers, shadows, guards, moths ]
//
// A blocker is a short array whose first item says what it is:
//   ['H', x, y, w, h]  a hedge rectangle
//   ['W', x, y, w, h]  a stone wall rectangle
//   ['F', x, y, r]     a fountain circle
// A shadow pool is [x, y, r]. A guard is [loop, pace], where loop is the
// waypoint list and pace an optional speed multiplier (1 when omitted).
// A moth is [x, y].
//
// The numbers are the garden: blockers stop feet and lantern light,
// shadow pools slow suspicion, patrol loops are the puzzle. `buildGarden`
// below turns each row into the shape the game reads.

